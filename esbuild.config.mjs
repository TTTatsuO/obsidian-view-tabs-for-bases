import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// Local testing: after each build, copy the output into the plugin folders
// listed in OBSIDIAN_PLUGIN_DIR (separated like PATH).
const pluginDirs = (process.env.OBSIDIAN_PLUGIN_DIR ?? '').split(path.delimiter).filter(Boolean);
const outputs = ['main.js', 'manifest.json', 'styles.css'];

const copyToVaults = {
	name: 'copy-to-vaults',
	setup(build) {
		build.onEnd(async (result) => {
			if (result.errors.length > 0) return;
			for (const dir of pluginDirs) {
				await mkdir(dir, { recursive: true });
				for (const file of outputs) await copyFile(file, path.join(dir, file));
				console.log(`copied ${outputs.join(', ')} → ${dir}`);
			}
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: ['obsidian', 'electron', ...builtinModules],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [copyToVaults],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
