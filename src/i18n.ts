/** Strings for Obsidian's language: the exact code, then its base language (en-GB → en), then English. */
export function text(): Strings {
	const language = getLanguage();
	return STRINGS[language] ?? STRINGS[language.split('-')[0] ?? ''] ?? EN;
}
